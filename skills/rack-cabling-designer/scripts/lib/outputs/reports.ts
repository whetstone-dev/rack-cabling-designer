// Markdown reports: power budget and the as-built / design document that bundles everything.

import { powerData } from '../assets.ts'
import { md, mdTable } from '../escape.ts'
import type { Analysis } from '../validate.ts'
import { bomMd } from './bom.ts'
import { scheduleMd } from './schedule.ts'

const pct = (w: number, cap: number): string => `${Math.round((w / cap) * 100)}%`

export function powerMd(a: Analysis): string {
  const p = a.power
  const pdus = p.pdus.map((x) => [
    x.pdu.name ?? x.pdu.id, x.pdu.rack, x.pdu.feed, `${x.pdu.voltage} V ${x.pdu.maxAmps} A${x.pdu.phases === 3 ? ' 3φ' : ''}`,
    Math.round(x.capacityW), Math.round(x.usableW),
    `${Math.round(x.normalW)} (${pct(x.normalW, x.capacityW)})`,
    x.failoverFeed ? `${Math.round(x.failoverW)} (${pct(x.failoverW, x.capacityW)}) if ${x.failoverFeed} fails` : 'n/a',
    `${x.outletsUsed}/${x.outletsTotal}`,
  ])
  const racks = p.racks.map((r) => [r.rackId, Math.round(r.loadW), Math.round(r.btuPerHour)])
  const devices = p.devices.filter((d) => d.loadW > 0 || d.connected.length > 0).map((d) => [
    d.label, d.rack ?? '', d.hasData ? Math.round(d.loadW) : 'unknown', d.connected.map((c) => `${c.inlet}→${c.pdu} (${c.feed})`).join(', ') || 'not connected',
  ])
  return `## Power budget

Basis: equipment **${p.basis}** power · usable capacity = ${Math.round(p.derating * 100)}% of circuit rating (${md(powerData().deratingSource)}).
Load sharing: a device's load is split across its connected inlets; on a feed failure the surviving inlets carry it all.

### PDUs

${mdTable(['PDU', 'Rack', 'Feed', 'Rating', 'Capacity W', 'Usable W', 'Normal W', 'Worst failover W', 'Outlets'], pdus)}
### Racks

${mdTable(['Rack', 'Load W', 'Heat BTU/h'], racks)}
### Devices

${mdTable(['Device', 'Rack', 'Load W', 'Connections'], devices)}`
}

export function findingsMd(a: Analysis): string {
  return mdTable(['Severity', 'Code', 'Finding'], a.diagnostics.map((d) => [d.severity, d.code, d.message]))
}

export function rackTablesMd(a: Analysis): string {
  const parts: string[] = []
  for (const rack of a.index.racks.values()) {
    const occ = a.occupancy.get(rack.id)
    if (!occ) continue
    const rows: unknown[][] = []
    for (let u = rack.heightU; u >= 1; u--) {
      const cell = occ.cells[u - 1]
      const name = (ids: string[]): string => ids.map((id) => a.index.devices.get(id)?.label ?? a.index.pdus.get(id)?.name ?? id).join(' + ')
      if (cell.front.length || cell.rear.length) rows.push([`U${u}`, name(cell.front), name(cell.rear)])
    }
    const side = occ.sidePdus.map((p) => `${p.label} (${p.side}, feed ${p.feed})`).join(', ')
    parts.push(`### ${md(rack.name ?? rack.id)}\n\n${rack.heightU}U${rack.location ? ` · ${md(rack.location)}` : ''}${side ? ` · 0U PDUs: ${md(side)}` : ''}\n\n${mdTable(['Unit', 'Front', 'Rear'], rows)}`)
  }
  return parts.join('\n')
}

export function documentMd(a: Analysis): string {
  const m = a.model
  const kind = m.meta.status === 'as-built' ? 'As-built documentation' : m.meta.status === 'change' ? 'Change design' : 'Design documentation'
  return `# ${md(m.meta.name)}

${kind}${m.meta.site ? ` · ${md(m.meta.site)}` : ''}${m.meta.revision ? ` · revision ${md(m.meta.revision)}` : ''}${m.meta.author ? ` · ${md(m.meta.author)}` : ''}

${m.meta.description ? `${md(m.meta.description)}\n\n` : ''}> Generated by rack-cabling-designer from \`${md(m.meta.name)}\`. This is a planning aid: verify dimensions, weights, power figures, cable lengths and optics against datasheets and the site, and have electrical work reviewed by qualified personnel.

## Summary

| Racks | Devices | PDUs | Cables | Channels | Errors | Warnings |
|---|---|---|---|---|---|---|
| ${a.index.racks.size} | ${m.devices.length} | ${a.index.pdus.size} | ${a.index.cables.length} | ${a.channels.length} | ${a.counts.error} | ${a.counts.warning} |

## Findings

${findingsMd(a)}
## Rack elevations

See \`elevation.html\` for the drawings.

${rackTablesMd(a)}
${powerMd(a)}
${scheduleMd(a)}
## Bill of materials

${bomMd(a)}
## Assumptions and limits

- Reach limits come from \`assets/data/media.json\` (nominal IEEE 802.3 / TIA values); fiber insertion-loss budgets, bend radius, fill ratios and PoE heating are **not** calculated.
- Power uses the declared equipment figures and an even load split across connected inlets.
- Equipment without declared weight, depth, power or airflow is reported as INCONCLUSIVE for that check.
`
}
